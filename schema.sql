-- 1 ----> WEBSITES
CREATE TABLE WEBSITES (
    WEBSITE_ID NUMBER PRIMARY KEY,
    URL VARCHAR2(500) NOT NULL,
    DOMAIN VARCHAR2(255) NOT NULL,
    ADDED_DATE DATE DEFAULT SYSDATE
);


--2 ----> RISK_INDICATORS مؤشر الخطورة
CREATE TABLE RISK_INDICATORS (
    INDICATOR_ID NUMBER PRIMARY KEY,
    INDICATOR_NAME VARCHAR2(100) NOT NULL,
    DESCRIPTION VARCHAR2(500),
    WEIGHT NUMBER NOT NULL
);


-- 3 -----> SCAN_RESULTS
CREATE TABLE SCAN_RESULTS (
    SCAN_ID NUMBER PRIMARY KEY,
    WEBSITE_ID NUMBER NOT NULL,
    SCAN_DATE DATE DEFAULT SYSDATE,
    RISK_LEVEL VARCHAR2(20) NOT NULL,
    RISK_SCORE NUMBER NOT NULL,

    CONSTRAINT FK_SCAN_WEBSITE
    FOREIGN KEY (WEBSITE_ID)
    REFERENCES WEBSITES(WEBSITE_ID)
);


-- 4 -------> SCAN_INDICATORS
CREATE TABLE SCAN_INDICATORS (
    SCAN_ID NUMBER,
    INDICATOR_ID NUMBER,
    IS_DETECTED CHAR(1) NOT NULL,

    CONSTRAINT PK_SCAN_INDICATORS
    PRIMARY KEY (SCAN_ID, INDICATOR_ID),

    CONSTRAINT FK_SI_SCAN
    FOREIGN KEY (SCAN_ID)
    REFERENCES SCAN_RESULTS(SCAN_ID),

    CONSTRAINT FK_SI_INDICATOR
    FOREIGN KEY (INDICATOR_ID)
    REFERENCES RISK_INDICATORS(INDICATOR_ID)
);